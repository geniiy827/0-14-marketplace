"""Split the 0.14 block/item atlases into one PNG per tile, and build the
"new textures" set from Java 1.19.4 assets.

  assets/textures/blocks/<name>.png          (one tile)
  assets/textures/blocks/<name>/<i>.png      (several variants, i = index in terrain.meta)
  assets/textures/items/...                  (same for items.meta)
  assets/textures_new/...                    (same layout, only tiles that have a new version)

At runtime NovaActivity (AtlasBuilder) puts the tiles back into the atlas the
engine reads, so packs can replace single tiles.

usage: gen_textures.py GAME_ASSETS JAVA_TEXTURES OUT_ASSETS
"""
import json, os, shutil, sys
from PIL import Image

SRC, JAVA, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from newtex_map import M

# Waving tiles move into a strip appended under the 512x256 block atlas (now 512x512),
# so shaders can tell them apart by uv.y alone (tools/../assets nova/shaderlib/atlas.h):
#   L  leaves/vines: every vertex sways              y 256..272
#   PT tops of double plants: rigid sway             y 280..296
#   P  plants/crops: top vertices sway, base fixed   rows every 24 px from y 304
WAVE_L = ['leaves', 'leaves_opaque', 'leaves2', 'leaves_opaque2', 'vine']
WAVE_PT = ['double_plant_top', 'sunflower_additional']
WAVE_P = ['tallgrass', 'flower1', 'flower2', 'sapling', 'wheat', 'carrots', 'potatoes', 'beetroot',
          'double_plant_bottom', 'nether_wart']
WAVE_STRIP = False   # shaders were removed; kept for a possible return
STRIP = {'L': 256, 'PT': 280, 'P': 304, 'P_PERIOD': 24, 'H': 512}


def relocate(entries):
    import copy
    old = copy.deepcopy(entries)
    W = entries[0]['uvs'][0][4]
    for e in entries:
        e['uvs'] = [[u[0], u[1], u[2], u[3], u[4], STRIP['H']] for u in e['uvs']]
    by = {e['name']: e for e in entries}
    for band, names, period in (('L', WAVE_L, 16), ('PT', WAVE_PT, 16), ('P', WAVE_P, STRIP['P_PERIOD'])):
        k = 0
        for n in names:
            for i in range(len(by[n]['uvs'])):
                x, y = (k % (W // 16)) * 16, STRIP[band] + (k // (W // 16)) * period
                if band != 'P':
                    assert k < W // 16, band
                by[n]['uvs'][i] = [x, y, x + 16, y + 16, W, STRIP['H']]
                k += 1
    return old


def atlas_header():
    return ('// generated by tools/gen_textures.py: waving tiles in the block atlas (pixels of a %d px high atlas)\n'
            '#define NOVA_ATLAS_H %d.0\n#define NOVA_WAVE_L %d.0\n#define NOVA_WAVE_PT %d.0\n'
            '#define NOVA_WAVE_P %d.0\n#define NOVA_WAVE_P_PERIOD %d.0\n'
            % (STRIP['H'], STRIP['H'], STRIP['L'], STRIP['PT'], STRIP['P'], STRIP['P_PERIOD']))


ATLASES = [('t', 'terrain.meta', 'terrain-atlas.tga', 'blocks'), ('i', 'items.meta', 'items-opaque.tga', 'items')]


def rel(name, i, n):
    return '%s/%d.png' % (name, i) if n > 1 else '%s.png' % name


def jtile(path):
    im = Image.open(os.path.join(JAVA, path + '.png')).convert('RGBA')
    w = im.size[0]
    return im.crop((0, 0, w, w))          # animated strips: first frame


def avg(im, mask=None):
    px = list(im.getdata())
    sel = [p for k, p in enumerate(px) if p[3] > 0 and (mask is None or mask[k])]
    if not sel:
        return (0, 0, 0)
    n = len(sel)
    return tuple(sum(p[c] for p in sel) / n for c in range(3))


def tint(gray, color):
    g = avg(gray)
    f = [color[c] / max(1.0, g[c]) for c in range(3)]
    out = gray.copy()
    out.putdata([(min(255, int(p[0] * f[0])), min(255, int(p[1] * f[1])), min(255, int(p[2] * f[2])), p[3])
                 for p in gray.getdata()])
    return out


def build_new(spec, old):
    size = old.size
    if isinstance(spec, str):
        return jtile(spec).resize(size, Image.NEAREST)
    kind = spec[0]
    if kind == 'tint':
        return tint(jtile(spec[1]), avg(old)).resize(size, Image.NEAREST)
    if kind == 'rot90':
        return jtile(spec[1]).transpose(Image.Transpose.ROTATE_90).resize(size, Image.NEAREST)
    if kind == 'opaque':
        t = jtile(spec[1])
        c = avg(old)
        bg = Image.new('RGBA', t.size, (int(c[0] * 0.55), int(c[1] * 0.55), int(c[2] * 0.55), 255))
        bg.alpha_composite(t)
        return bg.resize(size, Image.NEAREST)
    if kind == 'grass_side':
        base = jtile('block/grass_block_side')
        ov = jtile('block/grass_block_side_overlay')
        # biome colour of this variant: old tile's grass strip
        o = old.resize(base.size, Image.NEAREST)
        mask = [p[3] > 0 for p in ov.getdata()]
        col = avg(o, mask)
        base.alpha_composite(tint(ov, col))
        return base.resize(size, Image.NEAREST)
    if kind == 'potion':
        bottle = jtile(spec[1])
        ov = jtile('item/potion_overlay')
        o = old.resize(bottle.size, Image.NEAREST)
        mask = [p[3] > 0 for p in ov.getdata()]
        col = avg(o, mask)
        out = bottle.copy()
        out.alpha_composite(tint(ov, col))
        return out.resize(size, Image.NEAREST)
    raise ValueError(spec)


def main():
    for d in ('textures', 'textures_new'):
        p = os.path.join(OUT, d)
        if os.path.isdir(p):
            shutil.rmtree(p)
    stats = {}
    for tag, meta, atlas, folder in ATLASES:
        entries = json.load(open(os.path.join(SRC, 'images', meta)))
        src_entries = entries
        if tag == 't' and WAVE_STRIP:
            import copy
            src_entries = relocate(entries)            # stock positions, for cutting the tiles
            os.makedirs(os.path.join(OUT, 'images'), exist_ok=True)
            with open(os.path.join(OUT, 'images', meta), 'w') as f:      # what the engine reads
                json.dump(entries, f, separators=(',', ':'))
            shutil.copy(os.path.join(SRC, 'images', meta), os.path.join(OUT, 'images', 'old_' + meta))
            os.makedirs(os.path.join(OUT, 'nova', 'shaderlib'), exist_ok=True)
            with open(os.path.join(OUT, 'nova', 'shaderlib', 'atlas.h'), 'w') as f:
                f.write(atlas_header())
            entries = copy.deepcopy(entries)
        # the engine samples flowing water/lava from a 32x32 block (meta lists only its top-left 16x16)
        for lst in (entries, src_entries):
            for e in lst:
                if e['name'] in ('flowing_water', 'flowing_lava'):
                    e['uvs'] = [[u[0], u[1], u[2] + (u[2] - u[0]), u[3] + (u[3] - u[1]), u[4], u[5]] for u in e['uvs']]
        im = Image.open(os.path.join(SRC, 'images', atlas)).convert('RGBA')
        old_n = new_n = 0
        for e in src_entries:
            n = len(e['uvs'])
            for i, uv in enumerate(e['uvs']):
                x0, y0, x1, y1, W, H = uv
                sx, sy = im.size[0] / W, im.size[1] / H
                tile = im.crop((int(round(x0 * sx)), int(round(y0 * sy)), int(round(x1 * sx)), int(round(y1 * sy))))
                r = rel(e['name'], i, n)
                p = os.path.join(OUT, 'textures', folder, r)
                os.makedirs(os.path.dirname(p), exist_ok=True)
                tile.save(p)
                old_n += 1
                spec = M.get('%s:%s:%d' % (tag, e['name'], i))
                if spec is None:
                    continue
                try:
                    nt = build_new(spec, tile)
                except FileNotFoundError:
                    continue
                q = os.path.join(OUT, 'textures_new', folder, r)
                os.makedirs(os.path.dirname(q), exist_ok=True)
                nt.save(q)
                new_n += 1
        # layout for the runtime builder: meta + atlas size
        size = list(im.size)
        if tag == 't' and WAVE_STRIP:
            size[1] = size[0] * STRIP['H'] // entries[0]['uvs'][0][4]
        lay = {'atlas': 'images/' + atlas, 'size': size, 'folder': folder, 'entries': entries}
        with open(os.path.join(OUT, 'textures', folder + '.layout.json'), 'w') as f:
            json.dump(lay, f, separators=(',', ':'))
        stats[folder] = (old_n, new_n)
    print('tiles (old, new):', stats)


main()
