"""Menu music for NOVA (octa1): an original slow piece for note-block harp and bass, C418-like mood.
Writes native/menumusic.h: events {eighth, instrument, note index (0 = F#3 .. 24 = F#5), volume*100, flags}.
flag 1 = may be skipped at random (loops differ a little)."""
CH = {  # arpeggio voicings (harp) and bass roots (note.bass, two octaves lower)
 'Cmaj7': ([6, 13, 17, 22], 6), 'Em7': ([5, 10, 13, 20], 10), 'Am7': ([3, 10, 13, 18], 3),
 'Fmaj7': ([11, 15, 18, 22], 11), 'G6': ([5, 13, 20, 22], 1), 'Dm9': ([8, 11, 15, 22], 8)}
ARP = [(0, 0), (1, 1), (2, 2), (3, 3), (5, 2), (6, 1)]
bars = [  # chord, melody [(eighth, note)], arp volume
 ('Cmaj7', [], 18), ('Em7', [], 19), ('Am7', [], 20), ('Fmaj7', [], 20),
 ('Cmaj7', [(2, 22), (5, 20)], 21), ('Em7', [(0, 17), (4, 20), (6, 22)], 21),
 ('Am7', [(0, 18), (3, 17), (4, 15)], 21), ('Fmaj7', [(0, 17), (4, 18)], 20),
 ('Fmaj7', [(0, 22), (2, 23), (4, 22), (6, 20)], 21), ('G6', [(0, 20), (4, 17)], 21),
 ('Em7', [(0, 17), (2, 20), (4, 22)], 21), ('Am7', [(0, 20), (4, 18)], 20),
 ('Dm9', [(0, 23), (3, 22), (4, 20)], 21), ('G6', [(0, 22), (4, 20), (6, 17)], 20),
 ('Cmaj7', [(0, 18), (4, 22)], 19), ('Cmaj7', [(0, 18)], 17),
 ('Fmaj7', [], 15), (None, [], 0)]
ev = []
for b, (ch, mel, av) in enumerate(bars):
    t0 = b * 8
    if ch:
        v, root = CH[ch]
        ev.append((t0, 1, root, 26, 0))
        if av >= 19: ev.append((t0 + 4, 1, root, 14, 1))
        arp = ARP if b != 16 else ARP[:4]
        for p, i in arp: ev.append((t0 + p, 0, v[i], av, 0 if p == 0 else 1))
    for p, n in mel: ev.append((t0 + p, 0, n, 33, 0))
ev.sort()
with open('native/menumusic.h', 'w') as f:
    f.write('/* generated by tools/gen_menumusic.py */\n#define MM_EIGHTHS %d\n#define MM_N %d\n' % (len(bars) * 8, len(ev)))
    f.write('static const unsigned char MM_EV[MM_N][5] = {\n')
    f.write(',\n'.join('{%d,%d,%d,%d,%d}' % e for e in ev))
    f.write('};\n')
print(len(ev), 'events', len(bars) * 8 * 60 / 66 / 2, 's')
