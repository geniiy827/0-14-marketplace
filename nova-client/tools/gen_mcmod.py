"""McMod Script registry -> code + docs.

  mcmod/api/*.tsv (functions), mcmod/api/events.tsv (events), mcmod/prelude.mcs
  -> java/src/com/nova/client/mcmod/ApiTable.java
  -> native/mcmod_ops.h            (OP_* native operations, EV_* events)
  -> docs/MCMOD_API.md             (reference for people and AI)
  -> assets_new/nova/mcmod/prelude.mcs
"""
import os, re, shutil

W = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
API = os.path.join(W, 'mcmod', 'api')


def rows(path):
    for n, line in enumerate(open(path, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line.strip() or line.startswith('#'):
            continue
        cols = line.split('\t')
        yield n, cols


def main():
    funcs, events, ops = [], [], []
    for f in sorted(os.listdir(API)):
        if not f.endswith('.tsv'):
            continue
        p = os.path.join(API, f)
        for n, c in rows(p):
            if f == 'events.tsv':
                assert len(c) == 5, '%s:%d: need 5 columns' % (f, n)
                events.append(c)
                continue
            assert len(c) == 6, '%s:%d: need 6 columns, got %d' % (f, n, len(c))
            name, args, ret, impl, status, doc = c
            assert status in ('ok', 'wip', 'no'), '%s:%d: status' % (f, n)
            m = re.match(r'(native|nativestr):(\w+)(?:#(\d+))?(?::([\w,]+))?$', impl)
            if m:
                if m.group(2) not in ops:
                    ops.append(m.group(2))
                extra = m.group(4) or ''
                sub = extra if extra.isdigit() else '-1'
                keys = '' if extra.isdigit() else extra
                code = '%s:%d:%s:%s:%s' % ('s' if m.group(1) == 'nativestr' else 'n', ops.index(m.group(2)) + 1,
                                           m.group(3) or '-1', sub, keys)
            elif impl.startswith('java:'):
                code = impl
            elif impl == 'script':
                code = 'script:__' + name.replace('.', '_')
            else:
                raise SystemExit('%s:%d: bad impl %s' % (f, n, impl))
            funcs.append((name, args, ret, code, status, doc, f))
    names = [x[0] for x in funcs]
    dup = {x for x in names if names.count(x) > 1}
    assert not dup, 'duplicate functions: %s' % dup

    def jstr(s):
        return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

    j = ['package com.nova.client.mcmod;', '',
         '/** generated by tools/gen_mcmod.py from mcmod/api/*.tsv - do not edit */',
         'final class ApiTable {', '    private ApiTable() { }', '',
         '    /** name, args, returns, impl (n|s:op:index:subop:mapkeys | java:name | script:fn) */',
         '    static final String[][] FUNCS = {']
    for name, args, ret, code, status, doc, f in funcs:
        if status == 'no':
            continue
        j.append('        {%s, %s, %s, %s},' % (jstr(name), jstr(args), jstr(ret), jstr(code)))
    j += ['    };', '', '    /** event name, fields, cancelable; index + 1 = EV_* in native/mcmod_ops.h */',
          '    static final String[][] EVENTS = {']
    for name, fields, cancel, status, doc in events:
        j.append('        {%s, %s, %s},' % (jstr(name), jstr(fields), jstr(cancel)))
    j += ['    };', '}', '']
    open(os.path.join(W, 'java/src/com/nova/client/mcmod/ApiTable.java'), 'w').write('\n'.join(j))

    o = ['package com.nova.client.mcmod;', '', '/** generated by tools/gen_mcmod.py - native operation numbers */',
         'final class ApiOps {', '    private ApiOps() { }']
    for i, op in enumerate(ops, 1):
        o.append('    static final int %s = %d;' % (op, i))
    o += ['}', '']
    open(os.path.join(W, 'java/src/com/nova/client/mcmod/ApiOps.java'), 'w').write('\n'.join(o))

    h = ['/* generated by tools/gen_mcmod.py from mcmod/api - do not edit */']
    for i, o in enumerate(ops, 1):
        h.append('#define OP_%s %d' % (o, i))
    for i, e in enumerate(events, 1):
        h.append('#define EV_%s %d' % (re.sub(r'\W', '_', e[0]).upper(), i))
    open(os.path.join(W, 'native/mcmod_ops.h'), 'w').write('\n'.join(h) + '\n')

    st = {'ok': 'работает', 'wip': 'в работе', 'no': 'нет'}
    d = ['# McMod Script — функции и события', '',
         '_Сгенерировано из `mcmod/api/*.tsv` (tools/gen_mcmod.py). Статус: работает / в работе / нет._', '']
    by = {}
    for x in funcs:
        by.setdefault(x[0].split('.')[0] if '.' in x[0] else '(общие)', []).append(x)
    for g in sorted(by):
        d += ['## ' + g, '', '| функция | возвращает | статус | описание |', '|---|---|---|---|']
        for name, args, ret, code, status, doc, f in by[g]:
            a = '' if args == '-' else args
            d.append('| `%s(%s)` | %s | %s | %s |' % (name, a, ret, st[status], doc))
        d.append('')
    d += ['## События', '', '| событие | поля e | e.cancel() | статус | описание |', '|---|---|---|---|---|']
    for name, fields, cancel, status, doc in events:
        d.append('| `on %s(e)` | %s | %s | %s | %s |' % (name, fields, 'да' if cancel == 'yes' else '-', st[status], doc))
    os.makedirs(os.path.join(W, 'docs'), exist_ok=True)
    open(os.path.join(W, 'docs/MCMOD_API.md'), 'w').write('\n'.join(d) + '\n')

    out = os.path.join(W, 'assets_new/nova/mcmod')
    os.makedirs(out, exist_ok=True)
    shutil.copy(os.path.join(W, 'mcmod/prelude.mcs'), out)
    print('mcmod: %d functions, %d native ops, %d events' % (len(funcs), len(ops), len(events)))


main()
